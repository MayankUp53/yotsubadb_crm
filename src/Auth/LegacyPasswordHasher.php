<?php
declare(strict_types=1);

namespace App\Auth;

use Authentication\PasswordHasher\PasswordHasherInterface;

/**
 * Legacy Password Hasher
 * 
 * Supports both plain text passwords (legacy) and hashed passwords (new).
 * When a user successfully logs in with a plain text password, it will be
 * automatically hashed and updated in the database.
 */
class LegacyPasswordHasher implements PasswordHasherInterface
{
    /**
     * Default password hasher for new passwords
     * 
     * @var \Authentication\PasswordHasher\DefaultPasswordHasher
     */
    protected $defaultHasher;

    /**
     * Constructor
     */
    public function __construct()
    {
        $this->defaultHasher = new \Authentication\PasswordHasher\DefaultPasswordHasher();
    }

    /**
     * Generates password hash from plain text password.
     *
     * @param string $password Plain text password to hash.
     * @return string Password hash.
     */
    public function hash(string $password): string
    {
        return $this->defaultHasher->hash($password);
    }

    /**
     * Verifies that the provided password corresponds to its hashed version.
     *
     * @param string $password Plain text password to hash.
     * @param string $hashedPassword Existing hashed password.
     * @return bool True if password matches, false otherwise.
     */
    public function check(string $password, string $hashedPassword): bool
    {
        // Handle empty/null passwords
        if (empty($hashedPassword)) {
            return false;
        }

        // If the stored password looks like a hash (starts with $2y$ or similar), use default hasher
        if (preg_match('/^\$2[ayb]\$.{56}$/', $hashedPassword)) {
            return $this->defaultHasher->check($password, $hashedPassword);
        }

        // Otherwise, treat as plain text (legacy)
        return $password === $hashedPassword;
    }

    /**
     * Returns true if the password needs to be rehashed, due to the password being
     * created with anything else than the passwords generated by this class.
     *
     * @param string $password The password to verify.
     * @return bool True if the password needs to be rehashed.
     */
    public function needsRehash(string $password): bool
    {
        // If password is plain text (not a hash), it needs rehashing
        return !preg_match('/^\$2[ayb]\$.{56}$/', $password);
    }
}

